def env_list(name, default=''):
    return [value.strip() for value in config(name, default=default).split(',')
            if value.strip()]


def required_config(name):
    try:
        value = config(name)
    except UndefinedValueError as error:
        raise ImproperlyConfigured(
            f'{name} is required and cannot be empty'
        ) from error
    if not str(value).strip():
        raise ImproperlyConfigured(f'{name} is required and cannot be empty')
    return value


